"""
정보성 메시지 요건 검증 프롬프트
"""

def get_informational_message_validation_prompt(category: str, template_title: str, template_content: str) -> str:
    """정보성 메시지 요건 검증 프롬프트 생성"""
    return f"""다음 알림톡 템플릿이 정보성 메시지 요건을 만족하는지 검증해주세요.

## 정보성 메시지 요건 (반드시 준수)
- 반드시 정보성 메시지여야 함
- 광고성 메시지는 불가
- 앱 설치 유도 문구 포함 불가
- 무료체험, 할인쿠폰, 포인트 적립, 경품 등 혜택 제공 안내 불가
- 개인정보 등록/특정 행위(회원가입, 클릭 등) 유도 불가
- 동의하지 않은 쿠폰 발급 안내 불가

## 허용되는 정보성 메시지 예시
- 거래 진행, 이용, 결제, 배송, 예약 등 서비스 이용 과정에 반드시 필요한 안내
- 이용자 요청에 의해 발송되는 정보 (견적서 등)
- 결제 내역, 요금 고지서, 보험료 안내 등 정기적·필수적 청구 정보
- 재화·서비스 이용 관련 변경 안내 (회원등급 변경, 포인트 소멸 등)
- 보증, 리콜, 안전·보안 관련 공지
- 고객이 유상 계약을 통해 수령할 권리가 있는 서비스 업데이트 등

## 허용되지 않는 정보성 메시지 예시
- 상품 가격 비교 안내
- 할인 항공권, 주식 투자 등 구매/투자 유도성 정보
- 구인구직 정보(정보 자체를 유상 제공하는 경우)

## 검증 대상 템플릿
카테고리: {category}
제목: {template_title}
내용: {template_content}

## 응답 형식 (JSON)
{{
    "is_valid": true/false,
    "violations": [
        {{
            "rule": "위반된 규칙",
            "reason": "위반 사유",
            "severity": "error/warning",
            "suggestion": "개선 방안"
        }}
    ],
    "overall_assessment": "전체적인 평가"
}}"""
